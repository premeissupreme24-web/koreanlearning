function localizeLearningData() {
  letterData.forEach((letter) => {
    const english = letterEnglishHints[letter.glyph] || [letter.exampleZh || letter.roman, letter.mnemonic];
    letter.exampleZhText = letter.exampleZh;
    letter.exampleEn = english[0];
    letter.mnemonicZh = letter.mnemonic;
    letter.mnemonicEn = english[1];
  });
  pronunciationRules.forEach((rule, index) => {
    const english = pronunciationRuleEnglish[index];
    rule.tagZh = rule.tag;
    rule.titleZh = rule.title;
    rule.noteZh = rule.note;
    if (english) {
      [rule.tagEn, rule.titleEn, rule.noteEn] = english;
    }
  });
  pronunciationContrastItems.forEach((item, index) => {
    const english = pronunciationContrastEnglish[index];
    item.titleZh = item.title;
    item.hintZh = item.hint;
    if (english) [item.titleEn, item.hintEn] = english;
  });
  vowelContrastItems.forEach((item, index) => {
    const english = vowelContrastEnglish[index];
    item.titleZh = item.title;
    item.hintZh = item.hint;
    if (english) [item.titleEn, item.hintEn] = english;
  });
  euiQuizItems.forEach((item, index) => {
    const english = euiQuizEnglish[index];
    item.promptZh = item.prompt;
    item.noteZh = item.note;
    if (english) [item.promptEn, item.noteEn] = english;
  });
}

function localized(item, baseField) {
  const suffix = appLanguage === "en" ? "En" : "Zh";
  return item?.[`${baseField}${suffix}`] ?? item?.[baseField] ?? "";
}

function applyTranslations() {
  document.documentElement.lang = appLanguage === "en" ? "en" : "zh-Hant";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === appLanguage);
  });
  const activeView = document.querySelector(".view-section.active")?.id || "roadmap";
  updateViewTitle(activeView);
}

function updateViewTitle(viewId) {
  document.querySelector(".topbar")?.classList.toggle("roadmap-mode", viewId === "roadmap");
  document.getElementById("viewKicker").textContent = t(`views.${viewId}.kicker`);
  document.getElementById("viewTitle").textContent = t(`views.${viewId}.title`);
}

